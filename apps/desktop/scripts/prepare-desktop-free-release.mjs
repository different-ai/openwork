#!/usr/bin/env node
// Derives this release's free Auto secret from the CI master key and writes it
// into the Electron main bundle in a split, masked form. The gateway derives the
// same secret from the version each proof claims, so this only ever proves
// "built by us as version X" and expires with the release support window.
import { randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { deriveReleaseSecret as deriveSharedReleaseSecret } from "@openwork/free-auto/node";

const CHUNK = 8;
// Fixed shuffle of the 8 stored parts (4 mask chunks, 4 masked-secret chunks).
const ORDER = Object.freeze([5, 0, 6, 3, 1, 7, 2, 4]);
const STABLE_VERSION = /^\d+\.\d+\.\d+$/;

export function deriveReleaseSecret(masterKey, version) {
  if (typeof masterKey !== "string" || masterKey.trim().length < 32) throw new Error("DESKTOP_FREE_RELEASE_KEY must be at least 32 characters.");
  if (typeof version !== "string" || !version) throw new Error("A release version is required.");
  // One derivation, shared with the gateway that checks the tags.
  return Buffer.from(deriveSharedReleaseSecret(masterKey, version));
}

function chunks(bytes) {
  const parts = [];
  for (let offset = 0; offset < bytes.length; offset += CHUNK) parts.push(Buffer.from(bytes.subarray(offset, offset + CHUNK)));
  return parts;
}

/** The generated module text. The secret appears nowhere in it, in any encoding. */
export function obfuscateReleaseSecret(secret, version, random = randomBytes) {
  if (!(secret instanceof Uint8Array) || secret.length !== 32) throw new Error("The release secret must be 32 bytes.");
  const mask = Buffer.from(random(32));
  const masked = Buffer.alloc(32);
  for (let index = 0; index < 32; index++) masked[index] = secret[index] ^ mask[index];
  const ordered = [...chunks(mask), ...chunks(masked)];
  const parts = ORDER.map((index) => ordered[index].toString("base64url"));
  return [
    "// Generated by scripts/prepare-desktop-free-release.mjs at build time. Do not edit or commit.",
    `export const version = ${JSON.stringify(version)};`,
    `const parts = ${JSON.stringify(parts)};`,
    `const order = ${JSON.stringify(ORDER)};`,
    "export function reveal() {",
    "  const ordered = [];",
    "  for (let index = 0; index < order.length; index++) ordered[order[index]] = Buffer.from(parts[index], \"base64url\");",
    "  const mask = Buffer.concat(ordered.slice(0, 4)), masked = Buffer.concat(ordered.slice(4));",
    "  const secret = Buffer.alloc(masked.length);",
    "  for (let index = 0; index < masked.length; index++) secret[index] = masked[index] ^ mask[index];",
    "  return secret;",
    "}",
    "",
  ].join("\n");
}

export function emptyReleaseModule(version) {
  return [
    "// Generated by scripts/prepare-desktop-free-release.mjs at build time. No release key was available.",
    `export const version = ${JSON.stringify(version)};`,
    "export function reveal() { return null; }",
    "",
  ].join("\n");
}

export function writeDesktopFreeReleaseModule({ masterKey, version, outPath, ci = Boolean(process.env.CI), random }) {
  const key = masterKey?.trim() || "";
  if (!key) {
    if (ci && STABLE_VERSION.test(version)) throw new Error(`A stable release (${version}) must carry a free Auto release tag; set DESKTOP_FREE_RELEASE_KEY.`);
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, emptyReleaseModule(version), "utf8");
    return { tagged: false };
  }
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, obfuscateReleaseSecret(deriveReleaseSecret(key, version), version, random), { encoding: "utf8", mode: 0o644 });
  return { tagged: true };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const desktopRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const outIndex = process.argv.indexOf("--outfile");
  const outPath = outIndex >= 0 ? resolve(process.argv[outIndex + 1]) : resolve(desktopRoot, "electron", "generated", "desktop-free-release.mjs");
  const version = JSON.parse(readFileSync(resolve(desktopRoot, "package.json"), "utf8")).version;
  const result = writeDesktopFreeReleaseModule({ masterKey: process.env.DESKTOP_FREE_RELEASE_KEY, version, outPath });
  console.log(`[desktop-free-release] ${result.tagged ? "tagged" : "untagged"} build for ${version}`);
}
