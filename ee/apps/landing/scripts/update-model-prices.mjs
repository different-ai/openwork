// Refreshes the committed model price snapshot used by the Claude Cowork cost
// calculator. Run manually (`pnpm --filter @openwork-ee/landing prices:update`)
// and commit the result. Never run at request time or during `next build`.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://models.dev/api.json";
const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, "..", "lib", "model-prices.generated.ts");

// Curated list: [provider id on models.dev, model id, label shown on the page].
// Claude models are the only ones Claude Cowork can use.
const curated = [
  ["anthropic", "claude-opus-5-5", "Claude Opus 5.5"],
  ["anthropic", "claude-sonnet-5", "Claude Sonnet 5"],
  ["anthropic", "claude-haiku-4-5", "Claude Haiku 4.5"],
  ["openai", "gpt-6-sol", "GPT-6 Sol"],
  ["openai", "gpt-6-luna", "GPT-6 Luna"],
  ["google", "gemini-3.1-pro-preview", "Gemini 3.1 Pro"],
  ["google", "gemini-3.8-flash", "Gemini 3.8 Flash"],
  ["deepseek", "deepseek-v4-pro", "DeepSeek V4 Pro"],
  ["deepseek", "deepseek-v4-flash", "DeepSeek V4 Flash"],
  ["zai", "glm-5.3", "GLM 5.3"],
  ["moonshotai", "kimi-k3", "Kimi K3"],
  ["minimax", "MiniMax-M3", "MiniMax M3"],
  ["alibaba", "qwen3.8-max", "Qwen3.8 Max"],
  ["xai", "grok-4.7", "Grok 4.7"],
  ["mistral", "mistral-medium-latest", "Mistral Medium"]
];

const response = await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`models.dev returned ${response.status}`);
const catalog = await response.json();

const models = curated.map(([provider, id, label]) => {
  const model = catalog[provider]?.models?.[id];
  const cost = model?.cost;
  if (!cost || typeof cost.input !== "number" || typeof cost.output !== "number") {
    throw new Error(`Missing price for ${provider}/${id} on models.dev`);
  }
  return {
    id,
    provider,
    providerName: catalog[provider].name ?? provider,
    label,
    input: cost.input,
    output: cost.output,
    // Some providers publish no cache price; the calculator then bills cached input at the input price.
    cacheRead: typeof cost.cache_read === "number" ? cost.cache_read : null,
    claude: provider === "anthropic"
  };
});

const fetchedAt = new Date().toISOString().slice(0, 10);
const source = `// Generated by scripts/update-model-prices.mjs from ${SOURCE}. Do not edit by hand.
import type { ModelPrice } from "./model-prices";

export const modelPricesFetchedAt = "${fetchedAt}";

export const modelPrices: ModelPrice[] = ${JSON.stringify(models, null, 2)};
`;

writeFileSync(target, source);
console.log(`[update-model-prices] wrote ${models.length} models to ${target}`);
