import { expect } from "vitest";
import { spec } from "@openwork/testkit";
import { browserTeaching } from "../worlds/browser-teaching.ts";

const test = spec.world(browserTeaching, { timeout: 240_000, needs: { placement: "local" }, resources: { surfaces: [], services: ["den"] } });

test("a member teaches and corrects a browser task in Workbot chat, then reuses the saved skill", async ({ world, user, probe, step, evidence }) => {
  const person = user.on(world.registry);
  await step("credentials echoed after their field is removed stay private across navigation", async () => {
    await user.click({ role: "button", label: "Teach Workbot" });
    await user.see({ role: "combobox", label: "Tab to teach" });
    await user.see({ text: "Blank page · Tab 1" });
    await person.navigate(world.privateUrl);
    await user.click({ role: "button", label: "Start teaching" });
    await user.see({ text: "You have browser control" });
    await user.click({ role: "button", label: "Select information" });
    await person.click({ text: "Unlabelled Example Person, 1970-01-01" });
    await probe.eventually(() => world.state(), { within: 10_000, label: "an unlabelled selected value is represented without its text", until: value => Boolean(value.demonstration?.steps.some(step => step.kind === "extract" && step.target?.name === "")) });
    expect(await world.recorded()).not.toContain("Unlabelled Example Person");
    await person.click({ role: "button", label: "Copy and clear" });
    await person.click({ role: "button", label: "Echo example-private-credential-719" });
    await person.click({ role: "link", label: "Next privacy page" });
    await person.click({ role: "button", label: "Echo example-private-credential-719" });
    await probe.eventually(() => world.state(), { within: 10_000, label: "both stale echoes are redacted", until: value => value.demonstration?.steps.filter(step => step.target?.name === "Echo [private]").length === 2 });
    await user.type({ role: "textbox", label: "Message Workbot" }, "Keep credentials private while documenting the public workflow.", { replace: true });
    await user.click({ role: "button", label: "Send" });
    await user.see({ text: "Explanation added to the conversation" });
    const privateDraft = await world.recorded();
    expect(privateDraft).not.toContain("example-private-credential-719");
    expect(privateDraft).not.toContain("unobserved-reset-token-8347");
    expect(privateDraft).not.toContain("unobserved-bearer-token-349");
    expect(privateDraft).not.toContain("opaque-bearer-token-742");
    expect(world.state().demonstration?.steps.filter(step => step.kind === "navigate").every(step => step.url === undefined)).toBe(true);
    expect(world.turns().at(-1)?.prompt).not.toContain("example-private-credential-719");
    expect(world.turns().at(-1)?.prompt).toContain("Echo [private]");
    expect(world.turns().at(-1)?.prompt).not.toContain("unobserved-reset-token-8347");
    expect(world.turns().at(-1)?.prompt).not.toContain("unobserved-bearer-token-349");
    expect(world.turns().at(-1)?.prompt).not.toContain("opaque-bearer-token-742");
    expect(world.turns().at(-1)?.prompt).not.toContain("Unlabelled Example Person");
    evidence.recordAssertionEvidence("Removed field values remain redacted after navigation", "Both trusted clicks retain only Echo [private]; the draft and teaching conversation contain no credential.", !JSON.stringify(world.state()).includes("example-private-credential-719") && !world.turns().at(-1)?.prompt.includes("example-private-credential-719"));
    await person.click({ role: "button", label: "Exceed privacy budget" });
    await person.click({ role: "link", label: "Continue privacy check" });
    await probe.eventually(() => world.state(), { within: 10_000, label: "privacy overflow conceals descriptors without invalidating the draft", until: value => Boolean(value.demonstration?.steps.some(step => step.target?.name === "[private]")) });
    expect(await world.recorded()).not.toContain("x".repeat(5000));
    await user.click({ role: "button", label: "Finish teaching" });
    await user.type({ role: "textbox", label: "Skill name" }, "Privacy boundary", { replace: true });
    await user.type({ role: "textbox", label: "When to use this skill" }, "Check which fields still need explanations.", { replace: true });
    await user.see({ text: "Explain how to locate each unlabeled selected field before saving." });
    evidence.recordAssertionEvidence("An incomplete extraction explains what must be fixed before saving", "The draft names the missing explanation and keeps the selected value private.", !privateDraft.includes("Unlabelled Example Person"));
    await user.screenshot();
    await user.click({ role: "button", label: "Discard demonstration" });
    await person.navigate("about:blank");
  });
  await step("before: the member chooses the browser tab to teach", async () => {
    await user.see({ role: "combobox", label: "Tab to teach" });
    await user.see({ text: "Blank page · Tab 1" });
    await user.click({ role: "button", label: "Start teaching" });
    await user.see({ text: "You have browser control" });
    evidence.recordAssertionEvidence("Recording starts only for the chosen tab", `phase=${world.state().demonstration?.phase}`, world.state().demonstration?.phase === "recording");
    await user.screenshot();
  });
  await step("the member demonstrates a search and explains the changing input alongside it", async () => {
    await user.type({ role: "textbox", label: "Message Workbot" }, "I will show you how to search this registry and collect its status.", { replace: true });
    await user.click({ role: "button", label: "Send" });
    await user.see({ text: "Explanation added to the conversation" });
    expect(world.state().demonstration?.steps[0]?.kind).toBe("note");
    await person.navigate(world.registryUrl);
    await person.type({ role: "textbox", label: "Name" }, "example one", { replace: true });
    await person.click({ role: "button", label: "Search" });
    await person.see({ text: "Pending" });
    await probe.eventually(() => world.state(), { within: 10_000, label: "the semantic field edit is recorded", until: value => Boolean(value.demonstration?.steps.some(step => step.kind === "fill")) });
    await user.type({ role: "textbox", label: "Message Workbot" }, "Use a different person name each time. Ask me when several matches remain.", { replace: true });
    await user.click({ role: "button", label: "Send" });
    await user.see({ text: "Explanation added to the conversation" });
    await user.click({ text: /^Recorded steps/ });
    await user.click({ role: "button", label: /Enter Name/ });
    await user.type({ role: "textbox", label: "Input name" }, "Person name", { replace: true });
    await user.click({ role: "button", label: "Save step" });
    expect(world.state().demonstration?.steps.filter(step => step.kind === "fill")).toHaveLength(1);
    expect(world.turns().at(-1)?.readOnly).toBe(true);
    expect(world.turns().at(-1)?.prompt).toContain("[OpenWork browser teaching v2]");
    evidence.recordAssertionEvidence("The explanation reaches a read-only conversation with its recorded steps", `recorded steps=${world.state().demonstration?.steps.length}; readOnly=${world.turns().at(-1)?.readOnly}`, world.turns().at(-1)?.readOnly === true);
  });
  await step("the member selects the information to collect without recording its example value", async () => {
    await user.click({ role: "button", label: "Select information" });
    await person.click({ text: "Pending" });
    await person.see({ text: "Field not activated" });
    await person.notSee({ text: /^Field activated$/ });
    await user.see({ role: "button", label: /Collect Registration status/ });
    await user.click({ role: "button", label: /Collect Registration status/ });
    await user.type({ role: "textbox", label: "Output field" }, "Status", { replace: true });
    await user.click({ role: "button", label: "Save step" });
    const raw = await world.recorded();
    expect(raw).not.toContain("Example One"); expect(raw).not.toContain("example one"); expect(raw).not.toContain("fixture-secret-never-record"); expect(raw).not.toContain('"Pending"');
    evidence.recordAssertionEvidence("Extraction remembers the field label, while entered and protected values stay out", "Recorded Registration status; no example name, extracted value or password in the persisted demonstration.", !raw.includes("Example One") && !raw.includes("fixture-secret-never-record") && !raw.includes('"Pending"'));
    await user.screenshot();
  });
  await step("paused work and page-script clicks do not enter the demonstrated workflow", async () => {
    await user.click({ role: "button", label: "Pause recording" });
    const count = world.state().demonstration?.steps.length;
    expect(world.state().demonstration?.steps.some(step => step.target?.name === "Scripted decoy")).toBe(false);
    await person.type({ role: "textbox", label: "Name" }, "Paused private input", { replace: true });
    await person.click({ role: "button", label: "Search" });
    expect(world.state().demonstration?.steps).toHaveLength(count ?? 0);
    evidence.recordAssertionEvidence("Only demonstrated trusted input is included", `steps before/after paused activity=${count}/${world.state().demonstration?.steps.length}`, count === world.state().demonstration?.steps.length);
  });
  await step("the member corrects an earlier step in chat while recording is paused", async () => {
    await user.click({ role: "button", label: /Enter Name/ });
    await user.see({ text: /Recording paused.*Still teaching/ });
    await user.type({ role: "textbox", label: "Message Workbot" }, "Use the full person name when checking the record.", { replace: true });
    await user.click({ role: "button", label: "Send" });
    await user.see({ role: "button", label: "Send again" });
    const focusedId = world.state().demonstration?.steps.find(step => step.kind === "fill")?.id;
    await user.click({ role: "button", label: "Send again" });
    await user.see({ text: "Explanation added to the conversation" });
    const focused = world.state().demonstration?.steps.find(step => step.id === focusedId);
    expect(focused?.explanation.match(/Use the full person name/g)).toHaveLength(1);
    expect(world.turns().at(-1)?.readOnly).toBe(true);
    expect(world.turns().at(-1)?.prompt).toContain('"phase":"paused"');
    expect(world.turns().at(-1)?.prompt).toContain(`"focusedStepId":${focusedId}`);
    await user.see({ role: "button", label: "Use current explanation" });
    await user.click({ role: "button", label: "Use current explanation" });
    evidence.recordAssertionEvidence("Retry keeps the correction on the selected step once", "The earlier Name step contains one correction; paused chat remains read-only and the editor shows the newer notes.", focused?.explanation.match(/Use the full person name/g)?.length === 1 && world.turns().at(-1)?.readOnly === true);
    await user.screenshot();
    await user.click({ role: "button", label: "Finish teaching" });
    await user.type({ role: "textbox", label: "Message Workbot" }, "If a record is missing, tell me rather than guessing.", { replace: true });
    await user.click({ role: "button", label: "Send" });
    await probe.eventually(() => world.turns().at(-1), { within: 10_000, label: "draft review stays in the same read-only teaching conversation", until: value => Boolean(value?.prompt.includes('"phase":"draft"')) });
    expect(world.turns().at(-1)?.readOnly).toBe(true);
    evidence.recordAssertionEvidence("Draft review remains in the same teaching conversation", "The final clarification reaches the focused draft step with read-only credentials.", world.turns().at(-1)?.readOnly === true);
  });
  await step("after: the reviewed demonstration is saved through the normal private Cloud skill tool", async () => {
    await user.type({ role: "textbox", label: "Skill name" }, "Registry lookup", { replace: true });
    await user.type({ role: "textbox", label: "When to use this skill" }, "Use when asked to look up a person in the example public registry.", { replace: true });
    await user.click({ role: "button", label: "Home" });
    await user.see({ text: "Reviewing the skill" });
    await user.click({ role: "button", label: "Browser" });
    await user.click({ role: "button", label: "Save private skill" });
    await user.see({ text: /Saved .*registry-lookup.*private skills/ }, { timeoutMs: 30_000 });
    const source = await world.savedSkill();
    expect(source).not.toContain(new URL(world.registryUrl).host);
    expect(source).toContain("Use the full person name"); expect(source).toContain("If a record is missing");
    expect(source).toContain("start_url"); expect(source).toContain("person_name"); expect(source).toContain("Registration status"); expect(source).not.toContain("Example One"); expect(source).not.toContain("Paused private input");
    evidence.recordAssertionEvidence("The saved skill is discoverable through the member's real get_skill tool", "Den returned the saved skill with its parameter, extraction field and teacher explanation.", source.includes("person_name") && source.includes("Ask me when several matches remain"));
    await user.screenshot();
  });
  await step("the saved skill runs through fresh browser targets with a new person name", async () => {
    await user.type({ role: "textbox", label: "Starting page" }, world.registryUrl, { replace: true });
    await user.type({ role: "textbox", label: "Person name" }, "Example Two", { replace: true });
    await user.click({ role: "button", label: "Run skill" });
    await user.see({ text: /Active/ }, { timeoutMs: 30_000 });
    expect(world.turns().at(-1)?.readOnly).toBe(false);
    await user.see({ text: "Run my registry-lookup skill." });
    await user.notSee({ text: /\[OpenWork browser skill run v1\]/ });
    const result = JSON.stringify(world.runResult());
    expect(result).toContain("Active"); expect(result).not.toContain("Pending");
    evidence.recordAssertionEvidence("A deterministic model re-reads the stored skill and executes the taught targets in the real browser", "The second lookup returned Active using a new input and fresh browser observations; no paid inference or VM was used.", result.includes("Active") && !result.includes("Pending"));
    await user.screenshot();
  });
});
